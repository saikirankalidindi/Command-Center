  /**
   * Format a date string to a human-readable format
   */
  function formatDate(dateStr, options = {}) {
    if (!dateStr) return '—';
    const date = new Date(dateStr);
    if (isNaN(date)) return '—';

    const defaults = { month: 'short', day: 'numeric' };
    const opts = { ...defaults, ...options };

    // Add year if not current year
    if (date.getFullYear() !== new Date().getFullYear()) {
      opts.year = 'numeric';
    }

    return date.toLocaleDateString('en-US', opts);
  }

  /**
   * Format a datetime to relative time (e.g., "2 hours ago")
   */
  function timeAgo(dateStr) {
    if (!dateStr) return '';
    const date = new Date(dateStr);
    const now = new Date();
    const diff = now - date;

    const seconds = Math.floor(diff / 1000);
    const minutes = Math.floor(seconds / 60);
    const hours = Math.floor(minutes / 60);
    const days = Math.floor(hours / 24);

    if (seconds < 60) return 'just now';
    if (minutes < 60) return `${minutes}m ago`;
    if (hours < 24) return `${hours}h ago`;
    if (days < 7) return `${days}d ago`;
    return formatDate(dateStr);
  }

  /**
   * Format a datetime for display (e.g., "Today at 3:00 PM")
   */
  function formatDateTime(dateStr) {
    if (!dateStr) return '—';
    const date = new Date(dateStr);
    if (isNaN(date)) return '—';

    const today = new Date();
    const tomorrow = new Date(today);
    tomorrow.setDate(tomorrow.getDate() + 1);
    const yesterday = new Date(today);
    yesterday.setDate(yesterday.getDate() - 1);

    const timeStr = date.toLocaleTimeString('en-US', { hour: 'numeric', minute: '2-digit' });

    if (date.toDateString() === today.toDateString()) return `Today at ${timeStr}`;
    if (date.toDateString() === tomorrow.toDateString()) return `Tomorrow at ${timeStr}`;
    if (date.toDateString() === yesterday.toDateString()) return `Yesterday at ${timeStr}`;

    return `${formatDate(dateStr)} at ${timeStr}`;
  }

  /**
   * Get time-based greeting
   */
  function getGreeting() {
    const hour = new Date().getHours();
    if (hour < 12) return 'Good morning';
    if (hour < 17) return 'Good afternoon';
    if (hour < 21) return 'Good evening';
    return 'Good night';
  }

  /**
   * Get today's date string (YYYY-MM-DD)
   */
  function today() {
    return new Date().toISOString().split('T')[0];
  }

  /**
   * Format today's date for display
   */
  function formatTodayFull() {
    return new Date().toLocaleDateString('en-US', {
      weekday: 'long',
      year: 'numeric',
      month: 'long',
      day: 'numeric'
    });
  }

  /**
   * Check if a date is overdue
   */
  function isOverdue(dateStr) {
    if (!dateStr) return false;
    return dateStr < today();
  }

  /**
   * Get days until a date
   */
  function daysUntil(dateStr) {
    if (!dateStr) return null;
    const target = new Date(dateStr);
    const now = new Date();
    const diff = Math.ceil((target - now) / 86400000);
    return diff;
  }

